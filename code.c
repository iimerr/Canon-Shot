// ---- Countdown timer settings ----
#define GAME_TIME_LIMIT   30              // seconds
#define TIMER_TICKS_PER_SEC  2            // Timer1 fires at 2 Hz (every 0.5s)
#define GAME_TIME_TICKS  (GAME_TIME_LIMIT * TIMER_TICKS_PER_SEC)

/*---------------------------------------------------------------------------
   Timer1 - 7-segment countdown, driven by hardware timer interrupt
   (0.5s per tick) instead of counting game-loop frames. g_Countdown
   counts DOWN from GAME_TIME_TICKS to 0 and then simply stops - unlike
   a free-running demo clock, a game round only needs to hit zero once.
---------------------------------------------------------------------------*/
volatile uint8_t g_Countdown = GAME_TIME_TICKS;

void TMR1_Callback(uint32_t u32Param)
{
	if (g_Countdown > 0)
		g_Countdown--;
}

/*---------------------------------------------------------------------------
   ADC7 (on-board VR1) -> cannon left/right position, in place of keypad
   left/right. No interrupt is used: continuous scan mode keeps
   ADC->ADDR[7] refreshed in hardware with zero CPU involvement, so the
   game loop just reads it directly each frame. (An earlier version used
   DrvADC_EnableADCInt() + a flag, but continuous-mode ADC refires its
   interrupt extremely fast, and that constant preemption was corrupting
   the timing-sensitive, bit-banged LCD drawing routines - the actual
   cause of the LCD glitching.)
---------------------------------------------------------------------------*/

/*---------------------------------------------------------------------------
   UART0 - score exchange with the other board (pin32 RX0 <-> other
   board's TX0, pin33 TX0 <-> other board's RX0). Each board sends its
   final score as an 8-byte packet "SCddddd" (ASCII digits, zero-padded
   to 5). The RX interrupt just buffers 8 bytes and parses them - same
   pattern as the Smpl_UART0 sample. g_OppScoreReady is cleared at the
   start of every round, so a packet left over from a previous match
   can never be mistaken for the current one.
---------------------------------------------------------------------------*/
volatile uint8_t  g_UartRxBuf[9];
volatile uint16_t g_UartRxBytes = 0;
volatile uint8_t  g_OppScoreReady = 0;
volatile int16_t  g_OppScore = 0;

void UART0_RxCallback(uint32_t u32IntStatus)
{
	uint8_t inChar[1];
	while (UART0->ISR.RDA_IF==1) {
		DrvUART_Read(UART_PORT0, inChar, 1);
		if (g_UartRxBytes < 8) {
			g_UartRxBuf[g_UartRxBytes] = inChar[0];
			g_UartRxBytes++;
		}
		if (g_UartRxBytes==8) {
			g_UartRxBuf[8] = '\0';
			g_OppScore = (int16_t)atoi((char*)&g_UartRxBuf[2]); // skip "SC" prefix
			g_OppScoreReady = 1;
			g_UartRxBytes = 0;
		}
	}
}

